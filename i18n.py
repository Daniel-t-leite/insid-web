def translate_term(text: Optional[str], lang: str = "pt") -> str:
    """Traduz termos técnicos de catálogo da base de dados quando o idioma ativo é inglês."""
    if text is None:
        return ""
    s = str(text)
    if lang != "en":
        return s
    key = s.strip().lower()
    return CATALOG_EN.get(key, s)


